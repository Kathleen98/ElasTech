package org.example.exercicios.estruturasDeDecisao;

public class Utilidades {

    public static void saudar(String name){
        System.out.println("Olá, " + name + "! Tudo bem?");
    }

    public static void dobro(int num){
        System.out.println(num * 2);
    }

    public static void calcMedia(double n1, double n2){
        System.out.println((n1 + n2) / 2);
    }

    public static void eMaiorDeIdade(int idade){
        System.out.println(idade >= 18);
    }

    public static void somar(int n1, int n2){
        System.out.println(n1 + n2);
    }

    public static void somar(int n1, int n2, int n3){
        System.out.println(n1 + n2 + n3);
    }

    public static void somar(double n1, double n2){
        System.out.println(n1 + n2);
    }

    public static void saudacao(){
        System.out.println("Olá!");
    }

    public static void saudacao(String name){
        System.out.println("Olá! " + name + "!");
    }
}
